SET search_path TO cairo_metro;

-- 1) Extend stations with the attributes from the analysis file
ALTER TABLE stations
    ADD COLUMN IF NOT EXISTS station_code       VARCHAR(10) UNIQUE,
    ADD COLUMN IF NOT EXISTS area_type          VARCHAR(30),
    ADD COLUMN IF NOT EXISTS purchasing_power   SMALLINT CHECK (purchasing_power BETWEEN 1 AND 3),
    ADD COLUMN IF NOT EXISTS is_terminus        BOOLEAN DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS transport_hub      BOOLEAN DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS near_university    BOOLEAN DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS near_market        BOOLEAN DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS near_govt_hospital BOOLEAN DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS tourist_heritage   BOOLEAN DEFAULT FALSE;

-- Stop order is not in the source file, so allow it to be filled later
ALTER TABLE line_stations ALTER COLUMN stop_order DROP NOT NULL;

-- 2) Ad-score results per station
CREATE TABLE IF NOT EXISTS station_scores (
    station_id          INT PRIMARY KEY REFERENCES stations(station_id) ON DELETE CASCADE,
    rank                SMALLINT NOT NULL UNIQUE,
    tier                VARCHAR(20) CHECK (tier IN ('Premium','High','Standard')),
    ad_score            NUMERIC(5,1),
    c_reach             NUMERIC(6,4),
    c_purchasing        NUMERIC(6,4),
    c_dwell             NUMERIC(6,4),
    c_poi               NUMERIC(6,4),
    c_environment       NUMERIC(6,4),
    target_audience     TEXT,
    best_advertisers    TEXT,
    recommended_formats TEXT
);

-- Clear previous load (keeps lookup tables)
TRUNCATE station_scores, station_ridership, line_stations RESTART IDENTITY;
DELETE FROM stations;
ALTER SEQUENCE stations_station_id_seq RESTART WITH 1;

